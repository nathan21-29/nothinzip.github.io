// Compile the attached map's closing phrase; no map fetch/parsing during startup.
import { readFileSync, writeFileSync } from 'node:fs';

const source = readFileSync(new URL('../assets/beatmaps/padoru-gift.osu', import.meta.url), 'utf8');
const section = name => source.split(`[${name}]`)[1].split(/\n\[/)[0].trim().split(/\r?\n/).filter(line => line && !line.startsWith('//'));
const difficulty = Object.fromEntries(section('Difficulty').map(line => line.split(':').map(value => value.trim())));
const timing = section('TimingPoints').map(line => line.split(',').map(Number));
let number = 0;
const objects = section('HitObjects').map((line, index) => {
  const [x, y, time, type, , curve, repeats, length] = line.split(',');
  number = (Number(type) & 4) ? 1 : number + 1;
  const object = { x: Number(x), y: Number(y), time: Number(time), number, key: index % 2 };
  if (Number(type) & 2) {
    const points = timing.filter(point => point[0] <= object.time);
    const beatLength = points.findLast(point => point[6] === 1)[1];
    const inherited = points.at(-1);
    const velocity = inherited[6] === 0 ? -100 / inherited[1] : 1;
    Object.assign(object, {
      curve, length: Number(length), repeats: Number(repeats),
      duration: Number(length) * Number(repeats) / (Number(difficulty.SliderMultiplier) * 100 * velocity) * beatLength,
      tickInterval: beatLength / Number(difficulty.SliderTickRate)
    });
  }
  return object;
});
// No-mod osu!stable ScoreV1 SS, including the part of the map before the clip.
// https://osu.ppy.sh/wiki/en/Gameplay/Score/ScoreV1/osu!
// https://github.com/ppy/osu/wiki/Anatomy-of-a-slider
const drainSeconds = (objects.at(-1).time - objects[0].time) / 1000;
const difficultyMultiplier = Math.round((Number(difficulty.HPDrainRate) + Number(difficulty.CircleSize)
  + Number(difficulty.OverallDifficulty) + Math.min(16, objects.length / drainSeconds * 8)) / 38 * 5);
const scoring = objects.flatMap(object => {
  if (!object.curve) return [{ time: object.time, kind: 'circle', key: object.key, value: 300, comboDelta: 1, judgement: true }];
  const events = [{ time: object.time, kind: 'head', key: object.key, value: 30, comboDelta: 1 }];
  const spanDuration = object.duration / object.repeats;
  for (let span = 0; span < object.repeats; span++) {
    for (let tick = object.tickInterval; tick < spanDuration - 10; tick += object.tickInterval) {
      events.push({ time: object.time + span * spanDuration + tick, kind: 'tick', value: 10, comboDelta: 1 });
    }
    if (span < object.repeats - 1) events.push({ time: object.time + (span + 1) * spanDuration, kind: 'repeat', value: 30, comboDelta: 1 });
  }
  const end = object.time + object.duration;
  events.push({ time: end - Math.min(36, object.duration / 2), kind: 'tail', value: 30, comboDelta: 1 });
  events.push({ time: end, kind: 'judgement', value: 300, comboDelta: 0, judgement: true });
  return events;
}).sort((a, b) => a.time - b.time);
let score = 0, combo = 0;
const keyPresses = [0, 0];
for (const event of scoring) {
  score += event.judgement ? Math.round(event.value * (1 + Math.max(0, combo - 1) * difficultyMultiplier / 25)) : event.value;
  combo += event.comboDelta;
  if (event.key !== undefined) keyPresses[event.key]++;
  Object.assign(event, { score, combo, keyPresses: [...keyPresses] });
}
const start = 26590;
const initial = scoring.findLast(event => event.time < start);
const data = {
  title: 'Turbo - PADORU / PADORU (Sotarks) [Gift]', beatmapId: 2245774,
  start, end: objects.at(-1).time, stackLeniency: .7,
  ss: {
    scoring: 'osu!stable ScoreV1', mods: 'NM', difficultyMultiplier,
    initial: { score: initial.score, combo: initial.combo, keyPresses: initial.keyPresses },
    finalScore: score, maxCombo: combo,
    events: scoring.filter(event => event.time >= start)
  },
  objects: objects.filter(object => object.time >= start).map(({ tickInterval, ...object }) => object)
};
writeFileSync(new URL('../intro-beatmap.js', import.meta.url), `/* Generated by scripts/prepare-intro-beatmap.mjs from the supplied Gift difficulty. */\nwindow.IntroBeatmap = Object.freeze(${JSON.stringify(data, null, 2)});\n`);
console.log(`Compiled ${data.objects.length} objects from ${data.start} to ${data.end} ms; NM SS ${score} score / ${combo}x.`);
