// Natural Earth 1:110m land, public domain:
// https://raw.githubusercontent.com/nvkelso/natural-earth-vector/master/geojson/ne_110m_land.geojson
// Usage: node scripts/prepare-photo-globe.mjs /path/to/ne_110m_land.geojson
import { readFile, writeFile } from 'node:fs/promises';
const input = process.argv[2];
if (!input) throw new Error('Pass the downloaded Natural Earth 1:110m land GeoJSON path.');
const source = JSON.parse(await readFile(input, 'utf8'));
const round = n => Math.round(n * 100) / 100;
function simplify(points, tolerance = .16) {
  if (points.length < 4) return points;
  const first = points[0], last = points.at(-1);
  const dx = last[0] - first[0], dy = last[1] - first[1];
  let maximum = tolerance * tolerance, split = 0;
  for (let i = 1; i < points.length - 1; i++) {
    const t = dx || dy ? Math.max(0, Math.min(1, ((points[i][0] - first[0]) * dx + (points[i][1] - first[1]) * dy) / (dx * dx + dy * dy))) : 0;
    const distance = (points[i][0] - first[0] - t * dx) ** 2 + (points[i][1] - first[1] - t * dy) ** 2;
    if (distance > maximum) { maximum = distance; split = i; }
  }
  return split ? [...simplify(points.slice(0, split + 1), tolerance).slice(0, -1), ...simplify(points.slice(split), tolerance)] : [first, last];
}
const land = source.features.filter(feature => feature.bbox[3] > -55).flatMap(feature => {
  const polygons = feature.geometry.type === 'Polygon' ? [feature.geometry.coordinates] : feature.geometry.coordinates;
  return polygons.map(polygon => polygon[0]);
}).filter(ring => !ring.every(([lon, lat]) => lon > 128 && lon < 147 && lat > 30 && lat < 46))
  .map(ring => simplify(ring).map(point => point.map(round))).filter(ring => ring.length > 3);
// Use the exact detailed Japan outline of the destination map for a seamless landing.
const japanSVG = await readFile(new URL('../assets/japan.svg', import.meta.url), 'utf8');
const japan = [...japanSVG.match(/<path d="([^"]+)"/)[1].matchAll(/M([^M]+)/g)].map(([, path]) =>
  [...path.matchAll(/(-?[\d.]+),(-?[\d.]+)/g)].map(([, x, y]) => [+(128 + (Number(x) - 20) / 33).toFixed(4), +(46 - (Number(y) - 20) / 40).toFixed(4)])
);
await writeFile(new URL('../photo-globe-data.js', import.meta.url), `/* Natural Earth land, public domain. Generated by scripts/prepare-photo-globe.mjs. */\nwindow.PHOTO_GLOBE_DATA=${JSON.stringify({ land, japan })};\n`);
console.log(`Prepared ${land.length} land rings and ${japan.length} Japan islands.`);
